#!/usr/bin/env python3
"""Generate the six fixed DASH samples for the download integration gate.

Runs FFmpeg once per track (segmented 1s + full-length 4s), then emits six
hand-written MPDs that address the same media in different ways:

  1. number.mpd          - SegmentTemplate $Number$, count derived from the
                           root mediaPresentationDuration
  2. time.mpd            - SegmentTemplate + SegmentTimeline entries
  3. list.mpd            - SegmentList with explicit SegmentURLs
  4. multirep.mpd        - two video Representations + audio; the executor
                           must select the highest (height, bandwidth)
  5. adaptation.mpd      - SegmentTemplate at AdaptationSet level, inherited
                           by two Representations
  6. single-segment.mpd  - one 4s segment per track (single timeline entry)

Generated bytes are reproducible (lavfi sources) and never committed; only
this generator is source.
"""

import argparse
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def run_ffmpeg(args: list[str]) -> None:
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stderr[-2000:])
        raise SystemExit(f"ffmpeg failed: {' '.join(args[:6])}...")


def generate_track(out_dir: Path, prefix: str, video_args: list[str], seg_duration: int) -> tuple[int, int]:
    """Produce init + media segments; return (timescale, segment_duration)."""
    manifest = out_dir / f"{prefix}.mpd"
    run_ffmpeg([
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        *video_args,
        "-f", "dash", "-seg_duration", str(seg_duration),
        "-window_size", "0", "-remove_at_exit", "0",
        "-init_seg_name", f"{prefix}-init.mp4",
        "-media_seg_name", f"{prefix}-$Number$.m4s",
        "-use_template", "1", "-use_timeline", "0",
        str(manifest),
    ])
    text = manifest.read_text()
    match = re.search(r'<SegmentTemplate[^>]*timescale="(\d+)"[^>]*duration="(\d+)"', text)
    if not match:
        # Attribute order is not guaranteed; try both orders.
        match = re.search(r'<SegmentTemplate[^>]*duration="(\d+)"[^>]*timescale="(\d+)"', text)
        if not match:
            raise SystemExit(f"could not read timescale/duration from {manifest}")
        return int(match.group(2)), int(match.group(1))
    return int(match.group(1)), int(match.group(2))


MPD_HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<MPD xmlns="urn:mpeg:dash:schema:mpd:2011" type="static" '
    'mediaPresentationDuration="PT4S" minBufferTime="PT1S" '
    'profiles="urn:mpeg:dash:profile:isoff-live:2011">\n'
)

VIDEO_REP = (
    '      <Representation id="{rid}" bandwidth="200000" width="160" height="120" '
    'codecs="avc1.64000d" mimeType="video/mp4">{body}\n      </Representation>\n'
)
AUDIO_REP = (
    '      <Representation id="{rid}" bandwidth="64000" audioSamplingRate="44100" '
    'codecs="mp4a.40.2" mimeType="audio/mp4">{body}\n      </Representation>\n'
)


def timeline_body(prefix: str, timescale: int, seg_duration: int, count: int) -> str:
    # Segment count and timing come from the timeline; the media template uses
    # $Number$ because $Time$ substitutes the segment START TIME, which does
    # not match the muxer's sequential file names.
    entries = "".join(
        f'<S{" t=\"" + str(index * seg_duration) + "\"" if index == 0 else ""} d="{seg_duration}"/>'
        for index in range(count)
    )
    return (
        f'\n        <SegmentTemplate timescale="{timescale}" '
        f'initialization="{prefix}-init.mp4" media="{prefix}-$Number$.m4s" startNumber="1">\n'
        f'          <SegmentTimeline>{entries}</SegmentTimeline>\n'
        f'        </SegmentTemplate>\n'
    )


def number_body(prefix: str, timescale: int, seg_duration: int) -> str:
    return (
        f'\n        <SegmentTemplate timescale="{timescale}" duration="{seg_duration}" '
        f'initialization="{prefix}-init.mp4" media="{prefix}-$Number$.m4s" startNumber="1"/>\n'
    )


def list_body(prefix: str, count: int) -> str:
    urls = "".join(f'\n          <SegmentURL media="{prefix}-{index}.m4s"/>' for index in range(1, count + 1))
    return (
        f'\n        <SegmentList duration="0">\n'
        f'          <Initialization sourceURL="{prefix}-init.mp4"/>{urls}\n'
        f'        </SegmentList>\n'
    )


def write_mpd(path: Path, periods: str) -> None:
    path.write_text(MPD_HEADER + periods + "</MPD>\n")


def adaptation_set(inner: str) -> str:
    """Wrap representations in the AdaptationSet the parser requires."""
    return ('     <AdaptationSet mimeType="video/mp4" segmentAlignment="true">\n'
            + inner
            + "     </AdaptationSet>\n")


def audio_adaptation_set(inner: str) -> str:
    return ('     <AdaptationSet mimeType="audio/mp4" segmentAlignment="true">\n'
            + inner
            + "     </AdaptationSet>\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, help="directory to fill with fixtures")
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise SystemExit("ffmpeg not found")

    video_source = ["-f", "lavfi", "-i", "testsrc=duration=4:size=160x120:rate=10",
                    "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
                    "-b:v", "200k", "-force_key_frames", "expr:gte(t,n_forced*1)"]
    audio_source = ["-f", "lavfi", "-i", "sine=frequency=440:duration=4",
                    "-c:a", "aac", "-b:a", "64k"]

    v_timescale, v_seg = generate_track(out, "v", video_source, 1)
    a_timescale, a_seg = generate_track(out, "a", audio_source, 1)
    vf_timescale, vf_seg = generate_track(out, "vf", video_source, 4)
    af_timescale, af_seg = generate_track(out, "af", audio_source, 4)

    # Count the media segments the muxer actually wrote.
    seg_count = len(list(out.glob("v-*.m4s")))
    if seg_count != 4:
        raise SystemExit(f"expected 4 video segments, found {seg_count}")

    # 1. number.mpd — $Number$ addressing, count from presentation duration.
    write_mpd(out / "number.mpd", " <Period>\n"
              + adaptation_set(VIDEO_REP.format(rid="v", body=number_body("v", v_timescale, v_seg)))
              + audio_adaptation_set(AUDIO_REP.format(rid="a", body=number_body("a", a_timescale, a_seg)))
              + " </Period>\n")

    # 2. time.mpd — explicit SegmentTimeline.
    write_mpd(out / "time.mpd", " <Period>\n"
              + adaptation_set(VIDEO_REP.format(rid="v", body=timeline_body("v", v_timescale, v_seg, 4)))
              + audio_adaptation_set(AUDIO_REP.format(rid="a", body=timeline_body("a", a_timescale, a_seg, 4)))
              + " </Period>\n")

    # 3. list.mpd — SegmentList with explicit SegmentURLs.
    write_mpd(out / "list.mpd", " <Period>\n"
              + adaptation_set(VIDEO_REP.format(rid="v", body=list_body("v", 4)))
              + audio_adaptation_set(AUDIO_REP.format(rid="a", body=list_body("a", 4)))
              + " </Period>\n")

    # 4. multirep.mpd — two video Representations; the executor picks the max.
    two_video = (
        VIDEO_REP.format(rid="v-low", body=number_body("v", v_timescale, v_seg))
        .replace('bandwidth="200000" width="160" height="120"', 'bandwidth="100000" width="160" height="120"')
        + VIDEO_REP.format(rid="v-high", body=number_body("v", v_timescale, v_seg))
    )
    write_mpd(out / "multirep.mpd", " <Period>\n"
              + '     <AdaptationSet mimeType="video/mp4" segmentAlignment="true">\n'
              + two_video
              + "     </AdaptationSet>\n"
              + audio_adaptation_set(AUDIO_REP.format(rid="a", body=number_body("a", a_timescale, a_seg)))
              + " </Period>\n")

    # 5. adaptation.mpd — template inherited from the AdaptationSet level.
    inherited = (
        f'\n      <SegmentTemplate timescale="{v_timescale}" duration="{v_seg}" '
        f'initialization="v-init.mp4" media="v-$Number$.m4s" startNumber="1"/>\n'
    )
    write_mpd(out / "adaptation.mpd", " <Period>\n"
              + '     <AdaptationSet mimeType="video/mp4" segmentAlignment="true">'
              + inherited
              + '      <Representation id="v" bandwidth="200000" width="160" height="120" codecs="avc1.64000d"/>\n'
              + "     </AdaptationSet>\n"
              + audio_adaptation_set(AUDIO_REP.format(rid="a", body=number_body("a", a_timescale, a_seg)))
              + " </Period>\n")

    # 6. single-segment.mpd — one 4s segment per track.
    write_mpd(out / "single-segment.mpd", " <Period>\n"
              + adaptation_set(VIDEO_REP.format(rid="vf", body=timeline_body("vf", vf_timescale, vf_seg, 1)))
              + audio_adaptation_set(AUDIO_REP.format(rid="af", body=timeline_body("af", af_timescale, af_seg, 1)))
              + " </Period>\n")

    print(f"generated 6 DASH samples in {out}")


if __name__ == "__main__":
    main()
